// Generates supabase/seed.sql from the current src/data/*.ts so the database starts with
// exactly what the site shows today. Safe to re-run: every insert skips rows that already exist.
// Usage: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { people } from '../src/data/people.ts';
import { projects } from '../src/data/projects.ts';
import { press, spokeAboutUs, mediaCoverage, pressArchive } from '../src/data/press.ts';
import { partners } from '../src/data/partners.ts';
import { testimonials } from '../src/data/testimonials.ts';
import { stats } from '../src/data/stats.ts';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const b = (v) => (v ? 'true' : 'false');
const out = [];
const add = (s) => out.push(s);

add('-- Generated by scripts/gen-seed.mjs from src/data/*.ts. Do not edit by hand.\n');

add('-- Projects');
projects.forEach((p, i) => {
  add(`insert into projects (slug, title, title_accent, status, year_start, date_label, city, summary, featured, cover, cover_hint, hero, intro, body, vision, stats, stats_note, gallery, documentary, partner_block, sort_order)
values (${q(p.slug)}, ${q(p.title)}, ${q(p.titleAccent ?? null)}, ${q(p.status)}, ${q(p.yearStart)}, ${q(p.dateLabel)}, ${q(p.city)}, ${q(p.summary)}, ${b(p.featured)}, ${j(p.cover)}, ${q(p.coverHint ?? null)}, ${j(p.hero ?? null)}, ${q(p.intro ?? null)}, ${q(p.body ?? null)}, ${q(p.vision ?? null)}, ${j(p.stats ?? null)}, ${q(p.statsNote ?? null)}, ${j(p.gallery ?? null)}, ${j(p.documentary ?? null)}, ${j(p.partner ?? null)}, ${i + 1})
on conflict (slug) do nothing;`);
});

add('\n-- Editions');
for (const p of projects) for (const e of p.editions ?? []) {
  add(`insert into editions (project_id, year, number, date_label, venue, event, conductor, description, credits, watch_url, upcoming)
select id, ${q(e.year)}, ${e.number}, ${q(e.date)}, ${q(e.venue)}, ${q(e.event)}, ${q(e.conductor)}, ${q(e.description)}, ${q(e.credits ?? null)}, ${q(e.watchUrl)}, ${b(e.upcoming)} from projects where slug = ${q(p.slug)}
on conflict (project_id, year) do nothing;`);
}

add('\n-- People');
for (const p of people) {
  add(`insert into people (slug, name, role, city, "group", project_id, edition, photo, bio, website, sort_order)
values (${q(p.slug)}, ${q(p.name)}, ${q(p.role)}, ${q(p.city)}, ${q(p.group)}, ${p.project ? `(select id from projects where slug = ${q(p.project)})` : 'null'}, ${q(p.edition ?? null)}, ${j(p.photo)}, ${q(p.bio)}, ${q(p.website)}, ${p.order})
on conflict (slug) do nothing;`);
}

add('\n-- Edition line-ups (linked to People by exact name when there is a match)');
for (const p of projects) for (const e of p.editions ?? []) {
  if (!e.lineup.length) continue;
  const rows = e.lineup.map((m, i) => `(${q(m.name)}, ${q(m.role)}, ${i + 1})`).join(', ');
  add(`insert into edition_lineup (edition_id, person_id, name, role, sort_order)
select e.id, (select pe.id from people pe where pe.name = m.name limit 1), m.name, m.role, m.ord
from editions e join projects p on p.id = e.project_id
cross join (values ${rows}) as m(name, role, ord)
where p.slug = ${q(p.slug)} and e.year = ${q(e.year)}
  and not exists (select 1 from edition_lineup l where l.edition_id = e.id);`);
}

add('\n-- Press and recognition');
for (const x of press) add(`insert into press_items (slug, date, date_label, kind, title, source, url, featured) values (${q(x.id)}, ${q(x.date)}, ${q(x.dateLabel)}, ${q(x.kind)}, ${q(x.title)}, ${q(x.by)}, ${q(x.url)}, ${b(x.featured)}) on conflict (slug) do nothing;`);

add('\n-- Media mentions');
[[spokeAboutUs, 'spoke_about_us'], ...mediaCoverage.map((m) => [m, 'coverage'])].forEach(([m, kind], i) =>
  add(`insert into media_mentions (slug, kind, outlet, url, language, sort_order) values (${q(m.id)}, ${q(kind)}, ${q(m.outlet)}, ${q(m.url)}, ${q(m.language)}, ${i + 1}) on conflict (slug) do nothing;`));

add('\n-- Press archive');
pressArchive.forEach((a, i) => add(`insert into press_archive (slug, title, date_label, links, sort_order) values (${q(a.id)}, ${q(a.title)}, ${q(a.date)}, ${j(a.links)}, ${i + 1}) on conflict (slug) do nothing;`));

add('\n-- Partners');
for (const p of partners) add(`insert into partners (slug, name, logo, url, tier, active, sort_order) values (${q(p.id)}, ${q(p.name)}, ${q(p.logo)}, ${q(p.url)}, ${q(p.tier)}, ${b(p.active)}, ${p.order}) on conflict (slug) do nothing;`);

add('\n-- Testimonials');
for (const t of testimonials) add(`insert into testimonials (slug, text, who, caption, photo, project_slug, published, home, sort_order) values (${q(t.id)}, ${q(t.text)}, ${q(t.who)}, ${q(t.caption)}, ${j(t.photo)}, ${q(t.project || null)}, ${b(t.published)}, ${b(t.home)}, ${t.order}) on conflict (slug) do nothing;`);

add('\n-- Stats');
for (const s of stats) add(`insert into stats (slug, n, label, sort_order) values (${q(s.id)}, ${q(s.n)}, ${q(s.label)}, ${s.order}) on conflict (slug) do nothing;`);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql: ${out.length} statements`);
